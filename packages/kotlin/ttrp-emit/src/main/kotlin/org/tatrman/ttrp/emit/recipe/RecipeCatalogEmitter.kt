package org.tatrman.ttrp.emit.recipe

import org.tatrman.ttrp.bundle.OutputColumn
import org.tatrman.ttrp.bundle.RecipeFingerprints
import org.tatrman.ttrp.graph.recipe.RecipeModel

/**
 * A recipe's generated catalog (AU-core-P2 · S2.3 T4; D-25, D-27, D-77, D-105; contracts §5.3) — TTR-M the bundle
 * carries under `catalog/` and Veles serves once `/refresh` loads it: the recipe as an automation object, and the three
 * entities its writer keeps. TTR-M holds one `model` per file, so it is two files (a deviation from §5.3's one):
 *
 * - `catalog/<recipe>.ttrm` — `model automation`: `def recipe <name> { key, parameters, roles, routes, kinds, mode,
 *   document, fingerprints }`;
 * - `catalog/<recipe>_verdict.ttrm` — `model er`: `<recipe>_verdict` (run, as_of, the key, route, verdict_reason,
 *   parameters_fp, run_as, written_at — run, key and route its key), `<recipe>_verdict_detail` (run, the key, route,
 *   context, row_no — the writer numbers the rows, D-77 — and every `detail:` context's columns, as text) and
 *   `<recipe>_verdict_current` (the verdict's columns: the latest run per key, all its routes — a table the writer
 *   maintains, D-105, not a `def query`).
 *
 * The entities carry no er2db binding — like the automation stdlib, the deploying world's automation storage holds
 * them (§5.3's `automation_pg` binding is the world's, not the bundle's).
 */
object RecipeCatalogEmitter {
    data class Catalog(
        val recipeFile: String,
        val recipeText: String,
        val verdictFile: String,
        val verdictText: String,
    )

    fun emit(
        model: RecipeModel,
        keyTypes: List<String>,
        verdictColumns: List<OutputColumn>,
        detailColumns: List<OutputColumn>,
        document: String?,
        fingerprints: RecipeFingerprints,
    ): Catalog {
        val name = model.name
        val pkg = (model.programPackage ?: "automation") + ".generated"
        val header = "// GENERATED by `ttrp build` (AU-core-P2) from the recipe `$name` — do not edit; rebuild it.\n"
        val recipe =
            buildString {
                append(header)
                append("package $pkg\n")
                append("model automation\n\n")
                append("def recipe $name {\n")
                append("    key: ${list(model.keyAttributes)},\n")
                append("    parameters: ${list(model.parameters)},\n")
                model.candidates?.let { append("    candidates: $it,\n") }
                append("    contexts: ${list(model.contexts.map { it.name })},\n")
                model.decision?.let { append("    decision: $it,\n") }
                append("    routes: ${list(model.routes.map { it.name })},\n")
                append("    kinds: ${list(model.kinds.map { str(it) })},\n")
                append("    mode: ${str(model.mode.spelling)},\n")
                document?.let { append("    document: ${str(it)},\n") }
                append(
                    "    fingerprints: { text: ${str(fingerprints.text)}, values: ${str(fingerprints.values)}, " +
                        "labels: ${str(fingerprints.labels)} }\n",
                )
                append("}\n")
            }
        val keys = model.keyColumns.zip(keyTypes)
        val verdict =
            buildString {
                append(header)
                append("package $pkg\n")
                append("model er\n\n")
                entity(
                    this,
                    "${name}_verdict",
                    "The verdicts of the recipe `$name`: one row per run, key and route (D-27).",
                    verdictColumns,
                    keyOf =
                        keys.map { it.first } + listOf("run", "route"),
                )
                append('\n')
                entity(
                    this,
                    "${name}_verdict_detail",
                    "The rows of the `detail:` contexts the routes of `$name` attach, per run, key and route (D-77).",
                    detailColumns,
                    keyOf = emptyList(),
                )
                append('\n')
                entity(
                    this,
                    "${name}_verdict_current",
                    "The latest verdict per key of the recipe `$name`, all its routes (D-105).",
                    verdictColumns,
                    keyOf =
                        keys.map { it.first } + listOf("route"),
                )
            }
        return Catalog("catalog/$name.ttrm", recipe, "catalog/${name}_verdict.ttrm", verdict)
    }

    private fun entity(
        sb: StringBuilder,
        name: String,
        description: String,
        columns: List<OutputColumn>,
        keyOf: List<String>,
    ) {
        sb.append("def entity $name {\n")
        sb.append("    description: ${str(description)}\n")
        // CNC roles are retired (CN-D18); a generated entity must not introduce an unresolved legacy role.
        sb.append("    attributes: [\n")
        sb.append(
            columns.joinToString(",\n") { c ->
                val key = if (c.name in keyOf) ", isKey: true" else ""
                "        def attribute ${c.name} { type: ${c.type}$key }"
            },
        )
        sb.append("\n    ]\n}\n")
    }

    private fun list(items: List<String>) = items.joinToString(", ", "[", "]")

    private fun str(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
}
