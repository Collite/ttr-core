package org.tatrman.concept.extract

import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import org.tatrman.concept.ResolvedCnModel
import java.math.BigDecimal
import java.security.MessageDigest
import java.util.Arrays

/** Which entity and kind a model-tier registry entry was rendered from (the registry's `rendered_from`). */
data class RenderedFrom(
    val entity: String,
    val kind: TypeKind,
)

/**
 * One model-generated entry of the extraction pack's type registry (`types/registry.yaml` — contracts §6): its key
 * (`Statement[review]`, `Record.review`), its tier (always `model` here; the structural set is the engine's), the
 * unit it is extracted at, whether it feeds gold (a record does, a statement never), what it was rendered from, and
 * the rendered JSON Schema.
 */
data class TypeRegistryEntry(
    val key: String,
    val tier: String,
    val unitLevel: String,
    val feedsGold: Boolean,
    val renderedFrom: RenderedFrom,
    val schema: JsonObject,
)

/**
 * The generated half of a pack's type registry (⚑DX-P-2): for each entity, `types/generated/Statement.<e>.schema.json`
 * and `types/generated/Record.<e>.schema.json`, plus `types/generated/index.json` — every entry with its file's sha256,
 * and the content hash of the model it was rendered from (`snapshotHash`, ⚑R158-A: `cli.ModelContentHash.of` over the
 * model root — the same bytes give the same hash on any clone, and Pinakes recomputes it at pack load), so a registry
 * whose generated files do not match the pinned snapshot can refuse to load (contracts §6). Files are committed in the
 * pack (reviewable diffs), regenerated by `ttr cn render-types`.
 */
object TypeRegistryRenderer {
    const val DIR = "types/generated"

    /**
     * One Statement and one Record entry per entity [entities] names — each name resolved through
     * [SchemaRenderer.entity], a repeat (`review,er.entity.review`) kept once, at its first place.
     */
    fun entries(
        model: ResolvedCnModel,
        entities: List<String>,
        statementUnitLevel: String = "section",
    ): List<TypeRegistryEntry> {
        val renderer = SchemaRenderer(model)
        return entities.map(renderer::entity).distinctBy { it.qname }.flatMap { entity ->
            val name = entity.qname.name
            listOf(
                TypeRegistryEntry(
                    key = "Statement[$name]",
                    tier = "model",
                    unitLevel = statementUnitLevel,
                    feedsGold = false,
                    renderedFrom = RenderedFrom("er.entity.$name", TypeKind.STATEMENT),
                    schema = renderer.render(entity, TypeKind.STATEMENT),
                ),
                TypeRegistryEntry(
                    key = "Record.$name",
                    tier = "model",
                    unitLevel = "subject",
                    feedsGold = true,
                    renderedFrom = RenderedFrom("er.entity.$name", TypeKind.RECORD),
                    schema = renderer.render(entity, TypeKind.RECORD),
                ),
            )
        }
    }

    /**
     * Path under the pack root → JSON, the index included. [snapshotHash] is what the index pins — the model's
     * content hash (`cli.ModelContentHash.of(<model root>)`), never `ResolvedCnModel.snapshotHash` (a load's version:
     * absolute paths and mtimes, different on every clone — review-158 F2).
     */
    fun renderPack(
        model: ResolvedCnModel,
        entities: List<String>,
        snapshotHash: String,
    ): Map<String, JsonElement> {
        val entries = entries(model, entities)
        val files = sortedMapOf<String, JsonElement>()
        val index = mutableListOf<JsonElement>()
        for (e in entries.sortedBy { it.key }) {
            val file =
                SchemaRenderer.fileStem(e.renderedFrom.entity.substringAfterLast('.'), e.renderedFrom.kind) +
                    ".schema.json"
            files["$DIR/$file"] = e.schema
            index +=
                JsonObject(
                    sortedMapOf(
                        "key" to JsonPrimitive(e.key),
                        "tier" to JsonPrimitive(e.tier),
                        "unitLevel" to JsonPrimitive(e.unitLevel),
                        "feedsGold" to JsonPrimitive(e.feedsGold),
                        "renderedFrom" to
                            JsonObject(
                                sortedMapOf(
                                    "entity" to JsonPrimitive(e.renderedFrom.entity),
                                    "kind" to
                                        JsonPrimitive(
                                            e.renderedFrom.kind.name
                                                .lowercase(),
                                        ),
                                ),
                            ),
                        "file" to JsonPrimitive(file),
                        "sha256" to JsonPrimitive(sha256(SchemaJson.canonical(e.schema))),
                    ),
                )
        }
        files["$DIR/index.json"] =
            JsonObject(sortedMapOf("snapshotHash" to JsonPrimitive(snapshotHash), "types" to JsonArray(index)))
        return files
    }

    private fun sha256(text: String): String =
        MessageDigest
            .getInstance(
                "SHA-256",
            ).digest(text.toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it) }
}

/**
 * The canonical text of a generated file: keys sorted by code point, 2-space indent, `"key": value`, one array item per
 * line, non-ASCII verbatim, a trailing newline — `json.dumps(v, sort_keys=True, indent=2, ensure_ascii=False) + "\n"`,
 * so the Python worker and the Kotlin pipeline read and hash the same bytes (`canonical.sample.json`, shared with
 * kantheon's `CanonicalJson`, pins them). Python sorts `str` keys by code point, not by UTF-16 unit: `"！"` (U+FF01)
 * sorts before `"🙂"` (U+1F642, whose surrogate D83D a `String.compareTo` puts first). A number prints as its plain
 * numeral, never an exponent (`1E-7` → `0.0000001`) — Python re-prints a float's exponent differently (`1e-07`).
 */
object SchemaJson {
    fun canonical(element: JsonElement): String = buildString { write(element, 0) }.plus("\n")

    private fun StringBuilder.write(
        e: JsonElement,
        level: Int,
    ) {
        when (e) {
            is JsonObject ->
                if (e.isEmpty()) {
                    append("{}")
                } else {
                    append("{\n")
                    e.entries.sortedWith(compareBy(CODE_POINT_ORDER) { it.key }).forEachIndexed { i, (k, v) ->
                        if (i > 0) append(",\n")
                        indent(level + 1)
                        string(k)
                        append(": ")
                        write(v, level + 1)
                    }
                    append('\n')
                    indent(level)
                    append('}')
                }
            is JsonArray ->
                if (e.isEmpty()) {
                    append("[]")
                } else {
                    append("[\n")
                    e.forEachIndexed { i, v ->
                        if (i > 0) append(",\n")
                        indent(level + 1)
                        write(v, level + 1)
                    }
                    append('\n')
                    indent(level)
                    append(']')
                }
            JsonNull -> append("null")
            is JsonPrimitive -> if (e.isString) string(e.content) else append(plain(e.content))
        }
    }

    /** A literal as printed: a number with an exponent as its plain numeral, anything else (`true`, `12`) as is. */
    private fun plain(literal: String): String =
        if (literal.firstOrNull()?.let { it == '-' || it.isDigit() } == true &&
            literal.any { it == 'e' || it == 'E' }
        ) {
            BigDecimal(literal).toPlainString()
        } else {
            literal
        }

    private fun StringBuilder.indent(level: Int) {
        repeat(level) { append("  ") }
    }

    private fun StringBuilder.string(s: String) {
        append('"')
        for (ch in s) {
            when (ch) {
                '"' -> append("\\\"")
                '\\' -> append("\\\\")
                '\n' -> append("\\n")
                '\r' -> append("\\r")
                '\t' -> append("\\t")
                '\b' -> append("\\b")
                '\u000C' -> append("\\f")
                else -> if (ch < ' ') append("\\u%04x".format(ch.code)) else append(ch)
            }
        }
        append('"')
    }
}

/** Code-point order: Python's `sorted()` over `str`, and UTF-8 byte order — not [String.compareTo]'s UTF-16 units. */
internal val CODE_POINT_ORDER: Comparator<String> =
    Comparator { a, b -> Arrays.compare(a.codePoints().toArray(), b.codePoints().toArray()) }
