import { describe, it, expect } from 'vitest';
import type { LayoutDocument } from '@tatrman/parser/layout';
import { readYaml, writeYaml, yamlScalar, LAYOUT_YAML_HEADER } from '../layout-yaml.js';

const ITEM = 'hartland.er.entity.item';
const STORE = 'hartland.er.entity.store';
const SALES = 'hartland.er.entity.store_sales';

const POSITIONED: LayoutDocument = {
  name: 'sales_overview',
  model: 'er',
  objects: [SALES, ITEM, STORE],
  positions: { [STORE]: { x: 580, y: 180 }, [ITEM]: { x: 320, y: -40 } },
};

const DOCS: LayoutDocument[] = [
  POSITIONED,
  { name: 'empty', model: 'db', objects: [], positions: {} },
  { name: 'styled', model: 'er', objects: [ITEM, STORE], positions: {}, skin: 'er.crow', collapsed: [STORE] },
  { name: 'cz', model: 'er', objects: ['hartland.er.entity.zákazník', 'hartland.er.entity.důvod_reklamace'], positions: { 'hartland.er.entity.zákazník': { x: 1, y: 2 } } },
  { name: 'odd', model: 'er', objects: ['Customer Address', 'true', 'n'], positions: { 'Customer Address': { x: 0, y: 0 } } },
];

function read(text: string, fileName?: string) {
  const r = readYaml(text, { fileName });
  if (!r.ok) throw new Error(JSON.stringify(r.errors));
  return r;
}

describe('writeYaml (V-5, V-7)', () => {
  it('emits the canonical text: header, key order, block lists, flow positions, LF, trailing newline', () => {
    expect(writeYaml(POSITIONED)).toBe(
      [
        LAYOUT_YAML_HEADER,
        'layout: 1',
        'name: sales_overview',
        'model: er',
        'objects:',
        `  - ${ITEM}`,
        `  - ${STORE}`,
        `  - ${SALES}`,
        'positions:',
        `  ${ITEM}: { x: 320, y: -40 }`,
        `  ${STORE}: { x: 580, y: 180 }`,
        '',
      ].join('\n'),
    );
    expect(LAYOUT_YAML_HEADER).toBe('# Tatrman layout — https://docs.tatrman.org/model/layout-files/ (format 1)');
  });

  it('writes an empty card list as `objects: []` and omits empty optionals', () => {
    expect(writeYaml({ name: 'empty', model: 'db', objects: [], positions: {} })).toBe(
      `${LAYOUT_YAML_HEADER}\nlayout: 1\nname: empty\nmodel: db\nobjects: []\n`,
    );
  });

  it('writes skin, then collapsed, after positions', () => {
    const text = writeYaml({ ...POSITIONED, skin: 'er.crow', collapsed: [STORE] });
    expect(text.endsWith(`positions:\n  ${ITEM}: { x: 320, y: -40 }\n  ${STORE}: { x: 580, y: 180 }\nskin: er.crow\ncollapsed:\n  - ${STORE}\n`)).toBe(true);
  });

  it('puts the extra header lines (a generated layout) right after the first comment line', () => {
    const text = writeYaml(POSITIONED, { header: ['GENERATED by a tool — edit its source, not this file'] });
    expect(text.split('\n').slice(0, 3)).toEqual([
      LAYOUT_YAML_HEADER,
      '# GENERATED by a tool — edit its source, not this file',
      'layout: 1',
    ]);
  });

  it('canonicalizes on write: sorted, rounded, de-duplicated', () => {
    const messy: LayoutDocument = { ...POSITIONED, objects: [STORE, ITEM, SALES, ITEM], positions: { [STORE]: { x: 579.5, y: 180.4 }, [ITEM]: { x: 320, y: -40 } } };
    expect(writeYaml(messy)).toBe(writeYaml(POSITIONED));
  });

  it('emits diacritics raw — never a \\u escape', () => {
    const text = writeYaml(DOCS[3]);
    expect(text).toContain('  - hartland.er.entity.zákazník\n');
    expect(text).not.toMatch(/\\u/);
  });
});

describe('yamlScalar — plain when unambiguous in YAML 1.1 and 1.2, else double-quoted', () => {
  it('keeps identifiers, qnames and hyphenated ids plain', () => {
    for (const s of [ITEM, 'hartland.db.dbo.item', 'db.table-classic', 'zákazník', '_x', 'er']) expect(yamlScalar(s)).toBe(s);
  });

  it('quotes what YAML would read as something else, or cannot read plain', () => {
    expect(yamlScalar('true')).toBe('"true"');
    expect(yamlScalar('No')).toBe('"No"');
    expect(yamlScalar('n')).toBe('"n"');
    expect(yamlScalar('null')).toBe('"null"');
    expect(yamlScalar('1abc')).toBe('"1abc"');
    expect(yamlScalar('Customer Address')).toBe('"Customer Address"');
    expect(yamlScalar('say "hi" \\ bye')).toBe('"say \\"hi\\" \\\\ bye"');
  });
});

describe('readYaml (V-6, V-8)', () => {
  it('write → read → write is idempotent on canonical documents', () => {
    for (const d of DOCS) {
      const once = writeYaml(d);
      const back = read(once).doc;
      expect(writeYaml(back), d.name).toBe(once);
    }
  });

  it('reads flow style, quoted keys, comments anywhere and any key order the same as the canonical text', () => {
    const scrambled = [
      '# hand-written',
      'positions: {"hartland.er.entity.store": {y: 180, x: 580},   # a comment',
      `  ${ITEM}: { x: 320, y: -40 }}`,
      `objects: [${SALES}, "${STORE}", '${ITEM}']`,
      "model: 'er'",
      'name: sales_overview',
      'layout: 1  # format',
    ].join('\n');
    expect(read(scrambled).doc).toEqual(read(writeYaml(POSITIONED)).doc);
  });

  it('accepts decimals and rounds them (a reader accepts any number, V-3)', () => {
    const r = read(`layout: 1\nname: a\nmodel: er\nobjects: [${ITEM}]\npositions:\n  ${ITEM}: { x: 319.5, y: 10.2 }\n`);
    expect(r.doc.positions[ITEM]).toEqual({ x: 320, y: 10 });
  });

  it('refuses a newer format with exactly the V-6 message, before anything else', () => {
    const r = readYaml('layout: 2\nname: a\nmodel: er\nobjects: []\nfuture: yes\n');
    expect(r.ok).toBe(false);
    if (r.ok) return;
    expect(r.errors).toEqual([{ path: 'layout', message: 'layout format 2 is newer than this reader', line: 1 }]);
  });

  it('names an unknown root key and its line', () => {
    const r = readYaml('layout: 1\nname: a\nmodel: er\nobjects: []\nskinn: er.crow\n');
    expect(r.ok).toBe(false);
    if (r.ok) return;
    expect(r.errors).toEqual([{ path: 'skinn', message: 'unknown key `skinn`', line: 5 }]);
  });

  it('names an unknown key inside a position and its line', () => {
    const r = readYaml(`layout: 1\nname: a\nmodel: er\nobjects: [${ITEM}]\npositions:\n  ${ITEM}: { x: 1, y: 2, z: 3 }\n`);
    expect(r.ok).toBe(false);
    if (r.ok) return;
    expect(r.errors).toEqual([{ path: `positions.${ITEM}.z`, message: 'unknown key `z`', line: 6 }]);
  });

  it('V-3: a positions key not in objects is an error naming the key and its line', () => {
    const r = readYaml(`layout: 1\nname: a\nmodel: er\nobjects: [${ITEM}]\npositions:\n  ${STORE}: { x: 1, y: 2 }\n`);
    expect(r.ok).toBe(false);
    if (r.ok) return;
    expect(r.errors).toEqual([{ path: `positions.${STORE}`, message: `positions key ${STORE} is not in objects`, line: 6 }]);
  });

  it('requires layout, name, model and objects', () => {
    const r = readYaml('positions: {}\n');
    expect(r.ok).toBe(false);
    if (r.ok) return;
    expect(r.errors.map((e) => e.path)).toEqual(['layout', 'name', 'model', 'objects']);
  });

  it('reports wrong types with their paths', () => {
    const r = readYaml('layout: 1\nname: 12\nmodel: er\nobjects: [true, x]\npositions:\n  x: { x: "1", y: 2 }\n');
    expect(r.ok).toBe(false);
    if (r.ok) return;
    expect(r.errors.map((e) => [e.path, e.line])).toEqual([
      ['name', 2],
      ['objects[0]', 4],
      ['positions.x.x', 6],
    ]);
  });

  it('rejects a document that is not a mapping, or not YAML', () => {
    expect(readYaml('- a\n- b\n').ok).toBe(false);
    expect(readYaml('layout: 1\nname: [\n').ok).toBe(false);
    expect(readYaml('layout: 1\nlayout: 1\nname: a\nmodel: er\nobjects: []\n').ok).toBe(false);
  });

  it('a duplicate object is a warning, kept once', () => {
    const r = read(`layout: 1\nname: a\nmodel: er\nobjects: [${ITEM}, ${ITEM}]\n`);
    expect(r.doc.objects).toEqual([ITEM]);
    expect(r.warnings).toEqual([{ path: 'objects', message: `duplicate object ${ITEM} (kept once)` }]);
  });

  it('V-4/V-9: uses the in-document name, warns on a stem mismatch; .yml is just YAML', () => {
    const text = writeYaml(POSITIONED);
    expect(read(text, 'sales_overview.yaml').warnings).toEqual([]);
    expect(read(text, 'sales_overview.yml').warnings).toEqual([]);
    const r = read(text, 'downloads/sales_overview (1).yaml');
    expect(r.doc.name).toBe('sales_overview');
    expect(r.warnings).toEqual([{ path: 'name', message: 'file name sales_overview (1).yaml does not match the layout name sales_overview' }]);
  });
});
