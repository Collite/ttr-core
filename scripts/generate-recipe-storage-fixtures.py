"""Derive AU's independent storage fixtures from schema.sql and sample.sql.

Run with --check in CI/review to detect stale generated fixtures.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "packages/kotlin/ttrp-conform/src/test/resources/recipes/hartland"
LEDGER = {"obligation", "monitor_inbound_verdict"}


def statements(sql):
    """Split this fixture SQL outside strings/identifiers; discard line comments."""
    current = []
    quote = None
    i = 0
    while i < len(sql):
        char = sql[i]
        if quote:
            current.append(char)
            if char == quote:
                if i + 1 < len(sql) and sql[i + 1] == quote:
                    current.append(sql[i + 1])
                    i += 1
                else:
                    quote = None
        elif sql.startswith("--", i):
            end = sql.find("\n", i)
            i = len(sql) if end < 0 else end
            current.append("\n")
            continue
        elif char in "'\"":
            quote = char
            current.append(char)
        elif char == ";":
            text = "\n".join(line.rstrip() for line in "".join(current).splitlines()).strip()
            if text:
                yield text
            current = []
        else:
            current.append(char)
        i += 1
    if "".join(current).strip():
        raise ValueError("fixture ends without a semicolon")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    grouped = {"erp": [], "automation": []}
    for source in ("schema.sql", "sample.sql"):
        for statement in statements((FIXTURES / source).read_text()):
            match = re.match(r"(?:CREATE TABLE|INSERT INTO)\s+(\w+)\b", statement, re.I)
            if not match:
                raise ValueError(f"unclassified fixture statement: {statement[:80]}")
            storage = "automation" if match[1].lower() in LEDGER else "erp"
            grouped[storage].append(statement + ";")
    for storage, sql in grouped.items():
        path = FIXTURES / f"{storage}.sql"
        text = "-- GENERATED by scripts/generate-recipe-storage-fixtures.py; edit schema.sql / sample.sql.\n"
        text += "\n\n".join(sql) + "\n"
        if args.check:
            if path.read_text() != text:
                raise SystemExit(f"stale fixture: {path.relative_to(ROOT)}")
        else:
            path.write_text(text)


if __name__ == "__main__":
    main()
